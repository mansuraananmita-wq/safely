function ago(hours: number): string {
  return new Date(Date.now() - hours * 3_600_000).toISOString()
}

function dueFrom(created: string, hours: number): string {
  return new Date(new Date(created).getTime() + hours * 3_600_000).toISOString()
}

function act(id: string, hours: number, actor: string, visibility: Activity['visibility'], kind: Activity['kind'], message: string): Activity {
  return { id, at: ago(hours), actor, visibility, kind, message }
}

